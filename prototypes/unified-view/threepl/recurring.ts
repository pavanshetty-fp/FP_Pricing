/**
 * ONE DELIVERY IN A SERIES.
 *
 * Deliberately a SMALL record rather than a whole `BrokerOrder`. A generated
 * order really is a complete order in the product, but this screen only ever
 * shows six of its fields, and materialising 300 full orders to render 300
 * table cells would put a second, divergent copy of the orders fixture in the
 * prototype. Opening one is what hands the reader the real order.
 */
export interface Delivery {
  id: string;
  orderNo: string;
  dateKey: string;
  /** Formatted date over its relative label — the same cell the lists use. */
  date: TwoLine;
  status: BrokerStatus;
  vendorId: string | null;
  lines: OrderLine[];
  /**
   * TRUE ON THE ONE ROW THAT IS ALSO THE RECURRING ORDER. In V2 the first
   * delivery and the schedule are the same record, so this row is the parent
   * seen from below. It is flagged rather than dropped because hiding it would
   * hide the thing V1 exists to fix.
   */
  isParent: boolean;
  /** Cancelled by a pause, not by a person — restored when the pause lifts. */
  cancelledByPause: boolean;
}

/* ---------------------------------------------------------------------------
 * A series
 * ------------------------------------------------------------------------ */

export interface PauseRecord {
  fromKey: string;
  /** `null` is "until I say so" — the doc's Pause now. */
  toKey: string | null;
  by: string;
  at: string;
}

export interface RecurringSeries {
  id: string;
  /** The recurring order itself. It carries the schedule AND is delivery one. */
  parent: BrokerOrder;
  schedule: Schedule;
  /** The anchor: the parent's own delivery date. */
  startKey: string;
  /** `null` is the doc's "Never". */
  endKey: string | null;
  status: SeriesStatus;
  /**
   * WHY NOTHING IS BEING GENERATED, in plain words, or `null` when it is.
   *
   * Straight out of the doc's "When nothing gets created" table, which it
   * introduces as "the list to consult when a broker reports my orders stopped
   * appearing". Every one of those situations is silent in the product today —
   * logged, never shown. A row that says "Active" over an empty delivery list
   * and offers no reason is the single most expensive screen in this feature.
   */
  stalledReason: string | null;
  /** The rolling month, plus a short tail of delivered history. */
  deliveries: Delivery[];
  /** The next date an order will land on, or `null` when none will. */
  nextKey: string | null;
  pauses: PauseRecord[];
}

/** The rolling horizon the doc fixes: today through one month out. */
const HORIZON_DAYS = 31;

/** How much delivered history to keep on screen. */
const HISTORY_KEPT = 3;

/** Child numbers are drawn above every seeded one so they cannot collide. */
const CHILD_NO_BASE = 200_000;

function twoLineDate(d: Date, today: Date): TwoLine {
  const offset = Math.round(
    (startOfDay(d).getTime() - startOfDay(today).getTime()) / 86_400_000
  );
  return { title: DATE_FMT.format(d), description: relativeLabel(offset, d) };
}

function addDays(d: Date, n: number): Date {
  const out = new Date(d);
  out.setDate(out.getDate() + n);
  return out;
}

/**
 * Every date the schedule wants between two days, inclusive. Walking day by day
 * rather than stepping by the frequency is what makes one function serve all
 * five shapes — "first Thursday of the month" has no interval to step by.
 */
function datesBetween(schedule: Schedule, from: Date, to: Date): Date[] {
  const out: Date[] = [];
  for (let d = startOfDay(from); d <= to; d = addDays(d, 1)) {
    if (schedule.hits(d)) out.push(new Date(d));
  }
  return out;
}

/**
 * THE DELIVERED TAIL. A series that has been running has orders behind it, and
 * a list that starts at today reads as a series that started at today. Only
 * dates the schedule actually wanted, only before today, only the last few —
 * and never re-dated or moved by anything, which is the doc's own rule about
 * completed work.
 */
function history(
  schedule: Schedule,
  startKey: string,
  today: Date,
  seedIndex: number
): { date: Date; status: BrokerStatus }[] {
  const start = dayFromKey(startKey);
  if (start >= today) return [];
  const past = datesBetween(schedule, start, addDays(today, -1)).filter(
    (d) => dateKeyOf(d) !== startKey
  );
  /* The settled statuses, cycled by index so every one of them is reachable
     somewhere in the fixture rather than left to chance. */
  const settled: BrokerStatus[] = ["Completed", "Review", "Verified", "Synced"];
  return past.slice(-HISTORY_KEPT).map((d, k) => ({
    date: d,
    status: settled[(seedIndex + k) % settled.length],
  }));
}

/**
 * Builds one series from its recurring order.
 *
 * `override` is how the screen's own pause / end / cancel actions reach this —
 * the seed is static, so a broker pausing a series hands the change back in
 * here and the whole series is rebuilt from it. Rebuilding beats patching for
 * the reason the doc gives about schedule edits: the rules live in one place,
 * and a second place that decides which orders exist is a second place to get
 * it wrong.
 */
export interface SeriesOverride {
  cancelled?: boolean;
  endKey?: string | null;
  pauses?: PauseRecord[];
}

export function buildSeries(
  parent: BrokerOrder,
  seedIndex: number,
  today: Date,
  override: SeriesOverride = {}
): RecurringSeries {
  const startKey = parent.recurrence?.fromDateKey ?? parent.dateKey;
  const schedule = parseSchedule(
    parent.recurrence?.frequency ?? "Custom",
    startKey
  );
  const endKey = override.endKey ?? null;
  const pauses = override.pauses ?? [];
  const start = dayFromKey(startKey);
  const todayKey = dateKeyOf(today);

  /* ── The series' own state ──────────────────────────────────────────────
     Order matters. A cancelled series is cancelled whatever its dates say, a
     paused one is paused whatever its schedule says, and only then do the
     dates get a vote. */
  const activePause = pauses.find(
    (p) => p.fromKey <= todayKey && (p.toKey === null || p.toKey >= todayKey)
  );

  let status: SeriesStatus;
  if (override.cancelled || parent.status === "Cancelled") status = "Cancelled";
  else if (activePause) status = "Paused";
  else if (endKey && endKey < todayKey) status = "Ended";
  else if (start > today) status = "Upcoming";
  else status = "Active";

  /* An end date that arrived on its own is EXPIRED; one a person set and then
     passed is ENDED. Same dates, different stories — which is exactly the
     distinction the doc says must survive. */
  if (status === "Ended" && override.endKey === undefined) status = "Expired";

  /* ── Why it is producing nothing, if it is ───────────────────────────────
     The doc's table, in the doc's order. Only ONE reason is shown: a series
     that is both paused and unassigned is paused, and a list of every reason
     at once is a list nobody reads. */
  const vendorLocked = parent.vendorId !== null;
  let stalledReason: string | null = null;
  if (status === "Paused") {
    stalledReason = activePause?.toKey
      ? `Paused until ${DATE_FMT.format(dayFromKey(activePause.toKey))}`
      : "Paused — no resume date set";
  } else if (status === "Cancelled") {
    stalledReason = "Cancelled — the schedule is kept, generation stopped";
  } else if (status === "Ended" || status === "Expired") {
    stalledReason = "Past its end date";
  } else if (!vendorLocked) {
    /* THE ONE THE DOC CALLS OUT. Setup does not generate; a partner accepting
       does. Until then the series is healthy, visible, and silent. */
    stalledReason = "No partner assigned — nothing will be created yet";
  } else if (parent.status === "Blocked") {
    stalledReason = "The order is blocked on a credit issue";
  }

  /* ── The deliveries ─────────────────────────────────────────────────────
     History first, then the parent on its own date, then the rolling month.
     Nothing is generated at all unless a partner is locked in. */
  const deliveries: Delivery[] = [];

  history(schedule, startKey, today, seedIndex).forEach((h, k) => {
    deliveries.push({
      id: `${parent.id}-h${k}`,
      orderNo: `D-${CHILD_NO_BASE + seedIndex * 40 + k}`,
      dateKey: dateKeyOf(h.date),
      date: twoLineDate(h.date, today),
      status: h.status,
      vendorId: parent.vendorId,
      lines: parent.lines,
      isParent: false,
      cancelledByPause: false,
    });
  });

  deliveries.push({
    id: parent.id,
    orderNo: parent.orderNo,
    dateKey: startKey,
    date: twoLineDate(start, today),
    status: parent.status,
    vendorId: parent.vendorId,
    lines: parent.lines,
    isParent: true,
    cancelledByPause: false,
  });

  if (vendorLocked && status !== "Upcoming") {
    const from = start > today ? start : today;
    const to = addDays(today, HORIZON_DAYS);
    const wanted = datesBetween(schedule, from, to)
      /* THE PARENT'S OWN DATE IS SKIPPED — day one must not produce two. */
      .filter((d) => dateKeyOf(d) !== startKey)
      /* NEVER PAST THE END DATE. */
      .filter((d) => !endKey || dateKeyOf(d) <= endKey);

    wanted.forEach((d, k) => {
      const key = dateKeyOf(d);
      const inPause = pauses.some(
        (p) => p.fromKey <= key && (p.toKey === null || p.toKey >= key)
      );
      deliveries.push({
        id: `${parent.id}-g${k}`,
        orderNo: `D-${CHILD_NO_BASE + seedIndex * 40 + HISTORY_KEPT + k}`,
        dateKey: key,
        date: twoLineDate(d, today),
        /* THE DOC'S OWN WORD: a generated order arrives ready for the partner,
           which in this module's vocabulary is Assigned. */
        status: inPause ? "Cancelled" : "Assigned",
        vendorId: parent.vendorId,
        lines: parent.lines,
        isParent: false,
        cancelledByPause: inPause,
      });
    });
  }

  deliveries.sort((a, b) => a.dateKey.localeCompare(b.dateKey));

  const next =
    deliveries.find(
      (d) =>
        d.dateKey >= todayKey &&
        !isDelivered(d.status) &&
        d.status !== "Cancelled"
    )?.dateKey ?? null;

  return {
    id: parent.id,
    parent,
    schedule,
    startKey,
    endKey,
    status,
    stalledReason,
    deliveries,
    nextKey: next,
    pauses,
  };
}

/** How many orders of this series are still ahead — what the list counts. */
export function upcomingCount(s: RecurringSeries, today: Date): number {
  const key = dateKeyOf(today);
  return s.deliveries.filter(
    (d) => d.dateKey >= key && d.status !== "Cancelled" && !isDelivered(d.status)
  ).length;
}

/** The recurring orders in the fixture, in the order the board shows them. */
export const RECURRING_PARENTS: BrokerOrder[] = BROKER_ORDERS.filter(
  (o) => o.kind === "Recurring"
);

/** Free-text match — the same fields the orders list is findable by. */
export function matchesSeries(s: RecurringSeries, q: string): boolean {
  const needle = q.trim().toLowerCase();
  if (!needle) return true;
  return [
    s.parent.orderNo,
    s.parent.customer.title,
    s.parent.customer.description,
    s.parent.shipTo,
    s.schedule.label,
    s.status,
  ]
    .join(" ")
    .toLowerCase()
    .includes(needle);
}
