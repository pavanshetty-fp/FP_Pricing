/*
  RECURRING ORDERS — V1, THE RULE.

  THE ONE DIFFERENCE, AND EVERYTHING FOLLOWS FROM IT. In V2 the recurring order
  IS an order: it carries the schedule and it is also delivery one. Here the
  rule is not an order at all. It is a standing instruction that says WHO, WHAT,
  WHO HAULS IT, WHAT IT COSTS and HOW OFTEN — and every delivery, the first one
  included, is generated by it.

  WHAT THAT BUYS, in the order it shows up on screen:

    • NO DOUBLE LIFE. There is no row that is both the template and a delivery,
      so there is no "First delivery" badge to explain and no special case that
      skips day one to stop it being created twice.
    • EVERY DELIVERY IS A PEER. Cancel the first one and the rule is unharmed.
      In V2 that act is ambiguous — you canceled the schedule's own order.
    • THE CALENDAR CAN SHOW THE WHOLE SCHEDULE, not a rolling month. A rule
      knows every date it will ever want; only SOME of those dates have had an
      order cut for them yet. V2 cannot draw that distinction, because in V2 a
      date nobody has generated does not exist anywhere.
    • VERSIONING INSTEAD OF CLONING. The doc's "changing the vendor" and
      "changing products" both work today by creating a REPLACEMENT recurring
      order and leaving the old one behind as history. That is rule versioning
      wearing an order costume. Not modelled here yet — see the README.

  SAME DATA, BOTH VERSIONS. The rules below are built from the same seeded
  recurring orders V2 reads, deliberately: two screens over one fixture is what
  makes the comparison about the MODEL rather than about which one got the
  better sample.

  INVENTED, and flagged: the rule numbers, which deliveries count as tweaked,
  and the vendor POC (taken from the partner's dispatch contact, which is the
  person a delivery is actually arranged with).
*/

/** Where a scheduled date has got to. The four states a calendar cell can be. */
export type DeliveryState =
  /** On the rule, and far enough out that no order has been cut for it yet. */
  | "scheduled"
  /** An order exists and the work is still ahead. */
  | "created"
  /** An order exists, has run, and is being settled or is settled. */
  | "delivered"
  /** The rule wanted it; something stopped it. */
  | "skipped";

export interface RuleDelivery {
  dateKey: string;
  state: DeliveryState;
  /**
   * `null` until an order has actually been cut for this date.
   *
   * THIS IS THE FIELD V2 CANNOT HAVE. A date the rule wants but nobody has
   * generated is a real, nameable thing here — it is on the calendar, greyed,
   * with no number yet. In V2 the same date is simply absent.
   */
  orderNo: string | null;
  status: BrokerStatus | null;
  /**
   * WHAT SOMEBODY CHANGED ON THIS ONE DELIVERY, in plain words, or `null`.
   *
   * Editing one delivery never touches the rule or its siblings — that is the
   * whole point of a series being editable at all. But a delivery that no
   * longer matches the rule it came from has to SAY so, or the calendar is
   * lying about what the schedule produces.
   */
  tweak: string | null;
  /**
   * THIS DELIVERY'S OWN LINES, or `null` to mean "whatever the rule says".
   *
   * Null is not an empty order — it is the ordinary case, and storing a copy of
   * the rule's lines on every delivery would mean a change to the rule silently
   * failing to reach the deliveries that had never been touched. A delivery
   * takes its own copy at the moment somebody edits it and not before.
   */
  lines: OrderLine[] | null;
  /** Written for this delivery alone. Never reaches the rule or its siblings. */
  note: string;
  /**
   * WHERE THIS DELIVERY WAS BEFORE SOMEBODY DRAGGED IT.
   *
   * A hand-moved date is NOT part of the schedule. The doc is explicit that the
   * next time the rule itself is edited, a delivery sitting on a date the rule
   * does not produce is treated as unwanted and removed — so the move has to be
   * recorded as a move rather than quietly becoming the new truth.
   */
  movedFromKey: string | null;
}

export interface RecurringRule {
  id: string;
  /** `R-4821`. A RULE NUMBER, not an order number — the prefix is the point. */
  ruleNo: string;
  /**
   * WHEN THE RULE WAS SET UP. ISO.
   *
   * Not the same question as the start date, and the pair is worth having side
   * by side: a rule created in March to start in September is a booked
   * arrangement, and one created today to start today is somebody reacting.
   * Taken from the order's own trail rather than invented.
   */
  createdAt: string;

  /* ── Customer details ── */
  customer: TwoLine;
  shipTo: string;

  /* ── Delivery details ── */
  /**
   * NOT MANDATORY. A rule can name the tanks it fills, or it can name only the
   * product and leave the asset to the day. An empty list is a real answer
   * here, not a missing one, so it renders as "Any" rather than an em-dash.
   */
  assets: string[];
  lines: OrderLine[];

  /* ── Vendor details ── */
  vendorId: string | null;
  /** The person at the partner a delivery is arranged with. */
  vendorPoc: string | null;
  /**
   * WHETHER THE BROKER BUYS THE PRODUCT. Yes, and the rule has to say where it
   * is lifted from — terminal, supplier, loading account. No, and the partner
   * supplies it and none of those three fields means anything.
   */
  loadOrder:
    | { product: string; terminal: string; supplier: string; loadingAccount: string }[]
    | null;

  /* ── Pricing ── */
  /** What the partner charges for one delivery, all in. `null` = not priced. */
  vendorPrice: number | null;
  /**
   * What the customer is billed for one delivery, all in. `null` = NOT PRICED.
   *
   * Not zero. A rule whose lines carry no rate yet has no customer price, and
   * $0 is a number somebody will read as free — the one wrong answer that
   * looks like a real one. The delivery fee alone is not a price either: a
   * rule showing $125 for a 1,450-gallon drop is worse than one showing
   * nothing, because it invites the reader to believe it.
   */
  customerPrice: number | null;
  charges: OrderFee[];

  /* ── Who runs it ── */
  /**
   * BROKERAGE OR OUR OWN FLEET — the split the quick filters call third-party
   * and first-party operations. It decides whether this rule needs a partner
   * at all, which is why it cannot just be a label.
   */
  jobType: JobType;

  /* ── Where it sits in the business ── */
  /** Which line the rule runs on — the view bar's segments narrow by this. */
  serviceLine: ServiceLine;
  /** Which business inside that line. `null` on lines with none declared. */
  business: string | null;

  /* ── Schedule ── */
  schedule: Schedule;
  startKey: string;
  endKey: string | null;
  status: SeriesStatus;
  stalledReason: string | null;

  /** Every date the rule wants, from its start through a year out. */
  deliveries: RuleDelivery[];
  nextKey: string | null;
}

/** Rule numbers are their own band and their own prefix. */
const FIRST_RULE_NO = 4_800;

/** Order numbers cut by a rule sit above every seeded one. */
const RULE_ORDER_BASE = 300_000;

/**
 * HOW FAR THE CALENDAR CAN SEE — a year. Not a limit on the rule, which runs
 * until its end date; a limit on how much of it is worth materialising to draw
 * twelve months of cells.
 */
const CALENDAR_DAYS = 366;

/** How far ahead orders have actually been cut. The doc's rolling month. */
const GENERATED_DAYS = 31;

function dayFromKey(key: string): Date {
  const [y, m, d] = key.split("-").map(Number);
  return new Date(y, m - 1, d);
}

function addDays(d: Date, n: number): Date {
  const out = new Date(d);
  out.setDate(out.getDate() + n);
  return out;
}

/**
 * THE TWEAKS, SEEDED BY INDEX rather than drawn at random. Every state the
 * calendar distinguishes has to exist in the fixture or nobody can see whether
 * it works, and a random draw leaves that to chance. Three kinds, because they
 * are three different stories: a quantity somebody changed for one week, a date
 * somebody dragged, and a delivery somebody canceled on its own.
 */
const TWEAKS = [
  "Quantity changed for this delivery",
  "Date moved by hand",
  "Extra product line added",
];

export const RECURRING_RULES: RecurringRule[] = RECURRING_PARENTS.map(
  (seed: BrokerOrder, i): RecurringRule => {
    const today = startOfDay(new Date());
    const todayKey = dateKeyOf(today);
    const startKey = seed.recurrence?.fromDateKey ?? seed.dateKey;
    const schedule = parseSchedule(
      seed.recurrence?.frequency ?? "Custom",
      startKey
    );
    const vendor = VENDORS.find((v) => v.id === seed.vendorId) ?? null;

    /* ── The state of the rule itself ─────────────────────────────────────
       Simpler than V2's, and that is not an oversight — a rule has no order
       status of its own to reconcile against. It is running, not yet running,
       or stopped. */
    const start = dayFromKey(startKey);
    const canceled = seed.status === "Canceled";
    /* A FIRST-PARTY RULE NEEDS NO PARTNER. We are the haulier, so the thing
       that gates a brokerage rule — somebody accepting the lane — simply does
       not apply, and it generates from its start date. */
    const firstParty = seed.jobType === "Transportation";
    const priced = firstParty || seed.vendorId !== null;
    const status: SeriesStatus = canceled
      ? "Canceled"
      : start > today
        ? "Upcoming"
        : "Active";

    const stalledReason = canceled
      ? "Canceled — the rule is kept, generation stopped"
      : !priced
        ? "No partner assigned — nothing will be created yet"
        : seed.status === "Blocked"
          ? "The customer is blocked on a credit issue"
          : null;

    /* ── Every date the rule wants ────────────────────────────────────────
       A YEAR, NOT A MONTH. This is the thing the rule can do that the
       parent/child model cannot: name a date nobody has cut an order for. */
    const horizon = addDays(today, CALENDAR_DAYS);
    const generatedTo = addDays(today, GENERATED_DAYS);
    const deliveries: RuleDelivery[] = [];
    let n = 0;

    for (let d = start; d <= horizon; d = addDays(d, 1)) {
      if (!schedule.hits(d)) continue;
      const key = dateKeyOf(d);
      const past = key < todayKey;
      const generated = priced && !canceled && d <= generatedTo;

      /* Every seventh delivery carries a tweak, cycling the three kinds. */
      const tweak =
        (generated || past) && n % 7 === 3 ? TWEAKS[n % TWEAKS.length] : null;

      let state: DeliveryState;
      if (canceled && !past) state = "skipped";
      else if (past) state = "delivered";
      else if (generated) state = "created";
      else state = "scheduled";

      /* A delivery somebody canceled on its own — one per rule, so the state
         is reachable without pretending it is common. */
      if (state === "created" && n % 11 === 5) state = "skipped";

      deliveries.push({
        dateKey: key,
        state,
        orderNo:
          state === "scheduled"
            ? null
            : `D-${RULE_ORDER_BASE + i * 400 + n}`,
        status:
          state === "delivered"
            ? (["Completed", "Verified", "Synced"] as BrokerStatus[])[n % 3]
            : state === "skipped"
              ? "Canceled"
              : state === "created"
                ? "Assigned"
                : null,
        tweak,
        lines: null,
        note: "",
        movedFromKey: null,
      });
      n += 1;
    }

    const quote = seed.quotes.find((q) => q.vendorId === seed.vendorId) ?? null;

    return {
      id: `rule-${seed.id}`,
      ruleNo: `R-${FIRST_RULE_NO + i * 3}`,
      createdAt: seed.audit[0]?.at ?? new Date().toISOString(),
      customer: seed.customer,
      shipTo: seed.shipTo,
      /* THE ASSETS ARE THE TANKS THE LINES NAME. Every third rule is left
         open — no asset, product only — because "not mandatory" is a state the
         screen has to render and a fixture where every rule names one would
         never show it. */
      assets:
        i % 3 === 0 ? [] : [...new Set(seed.lines.map((l) => l.asset))],
      lines: seed.lines,
      vendorId: seed.vendorId,
      vendorPoc: vendor?.dispatchContactName ?? vendor?.mainContactName ?? null,
      loadOrder:
        seed.loadOrder
          ?.filter((r) => !r.excluded)
          .map((r) => ({
            product: r.product,
            terminal: r.terminal,
            supplier: r.supplier,
            loadingAccount: r.loadingAccount,
          })) ?? null,
      vendorPrice: quote ? quoteTotal(quote, seed.lines) : null,
      customerPrice: seed.lines.some((l) => l.pricePerGal != null)
        ? customerTotal(seed.lines, seed.orderFees)
        : null,
      charges: seed.orderFees,
      jobType: seed.jobType,
      serviceLine: seed.serviceLine,
      business: seed.business,
      schedule,
      startKey,
      endKey: null,
      status,
      stalledReason,
      deliveries,
      nextKey:
        deliveries.find((d) => d.dateKey >= todayKey && d.state !== "skipped")
          ?.dateKey ?? null,
    };
  }
);

/** Total gallons the rule asks for per delivery. Top-offs contribute nothing. */
export function ruleGallons(r: RecurringRule): number {
  return r.lines.reduce((sum, l) => sum + (l.topOff ? 0 : (l.gal ?? 0)), 0);
}

/** How many of this rule's dates have an order cut for them and still to run. */
export function ruleUpcoming(r: RecurringRule, todayKey: string): number {
  return r.deliveries.filter(
    (d) => d.dateKey >= todayKey && d.state === "created"
  ).length;
}

/** Free-text across everything the rule is findable by. */
export function matchesRule(r: RecurringRule, q: string): boolean {
  const needle = q.trim().toLowerCase();
  if (!needle) return true;
  return [
    r.ruleNo,
    r.customer.title,
    r.customer.description,
    r.shipTo,
    r.schedule.label,
    r.assets.join(" "),
    r.lines.map((l) => l.product).join(" "),
    VENDORS.find((v) => v.id === r.vendorId)?.name ?? "",
    r.vendorPoc ?? "",
    r.status,
  ]
    .join(" ")
    .toLowerCase()
    .includes(needle);
}

/** The rule's schedule as a sentence, for the sheet's header. */
export function ruleSentence(r: RecurringRule): string {
  const from = DATE_FMT.format(dayFromKey(r.startKey));
  return r.endKey
    ? `${r.schedule.label}, ${from} to ${DATE_FMT.format(dayFromKey(r.endKey))}`
    : `${r.schedule.label}, from ${from}`;
}

/* ---------------------------------------------------------------------------
 * The calendar
 * ------------------------------------------------------------------------ */

export interface CalendarCell {
  date: Date;
  dateKey: string;
  /** False for the leading and trailing days that pad the grid to whole weeks. */
  inMonth: boolean;
  delivery: RuleDelivery | null;
}

/**
 * Six weeks of cells, Sunday-first, covering the given month.
 *
 * ALWAYS SIX ROWS. A grid that is five rows in one month and six in the next
 * changes height as you step through it, and the thing under it moves while
 * you are reading it.
 */
export function monthGrid(
  rule: RecurringRule,
  year: number,
  month: number
): CalendarCell[] {
  const first = new Date(year, month, 1);
  const startsOn = new Date(year, month, 1 - first.getDay());
  const byKey = new Map(rule.deliveries.map((d) => [d.dateKey, d]));
  const out: CalendarCell[] = [];
  for (let i = 0; i < 42; i++) {
    const date = addDays(startsOn, i);
    const dateKey = dateKeyOf(date);
    out.push({
      date,
      dateKey,
      inMonth: date.getMonth() === month,
      delivery: byKey.get(dateKey) ?? null,
    });
  }
  return out;
}

/** The months this rule has anything to show, oldest first. */
export function ruleMonths(rule: RecurringRule): { year: number; month: number }[] {
  const seen = new Set<string>();
  const out: { year: number; month: number }[] = [];
  rule.deliveries.forEach((d) => {
    const date = dayFromKey(d.dateKey);
    const k = `${date.getFullYear()}-${date.getMonth()}`;
    if (seen.has(k)) return;
    seen.add(k);
    out.push({ year: date.getFullYear(), month: date.getMonth() });
  });
  return out;
}

/* ---------------------------------------------------------------------------
 * Editing ONE delivery
 * ------------------------------------------------------------------------ */

export interface DeliveryPatch {
  dateKey?: string;
  lines?: OrderLine[];
  note?: string;
  /** Skip this date, or put it back. */
  skipped?: boolean;
}

/**
 * Applies a change to one delivery and returns a NEW rule.
 *
 * CHANGES FLOW DOWNWARD ONLY, and this is the function that has to mean it.
 * Nothing here touches the rule's own schedule, lines, partner or price, and
 * nothing reaches the delivery's siblings. A broker who adds 500 gallons to
 * next Thursday has changed next Thursday.
 *
 * THE TWEAK LABEL IS DERIVED, NOT TYPED. What "changed" means is a comparison
 * between the delivery and the rule that made it, so it is computed here every
 * time rather than left to each caller to remember to set — a delivery whose
 * quantity was edited and then edited back is no longer tweaked, and only a
 * derived label can say so.
 */
export function editDelivery(
  rule: RecurringRule,
  dateKey: string,
  patch: DeliveryPatch
): RecurringRule {
  const moving =
    patch.dateKey !== undefined && patch.dateKey !== dateKey
      ? patch.dateKey
      : null;

  /* A MOVE ONTO AN OCCUPIED DATE IS NOT A MOVE. Two deliveries on one day is
     the duplicate the generator exists to prevent; refusing beats merging. */
  if (moving && rule.deliveries.some((d) => d.dateKey === moving)) return rule;

  const deliveries = rule.deliveries.map((d) => {
    if (d.dateKey !== dateKey) return d;

    const next: RuleDelivery = {
      ...d,
      dateKey: moving ?? d.dateKey,
      lines: patch.lines ?? d.lines,
      note: patch.note ?? d.note,
      movedFromKey: moving ? (d.movedFromKey ?? d.dateKey) : d.movedFromKey,
    };

    if (patch.skipped !== undefined) {
      next.state = patch.skipped
        ? "skipped"
        : next.orderNo
          ? "created"
          : "scheduled";
      /* CANCELLED IS AN ORDER'S STATUS, and a date nobody cut an order for
         has none. Skipping it takes it off the schedule; there is nothing to
         cancel, and a Canceled chip would name an order that never was. */
      next.status = !next.orderNo
        ? null
        : patch.skipped
          ? "Canceled"
          : "Assigned";
    }

    /* The label, recomputed from what is actually different. */
    const reasons: string[] = [];
    if (next.movedFromKey) {
      reasons.push(
        `Moved from ${DATE_FMT.format(dayFromKey(next.movedFromKey))}`
      );
    }
    if (next.lines && !sameLines(next.lines, rule.lines)) {
      reasons.push("Quantities changed for this delivery");
    }
    if (next.note.trim()) reasons.push("Has a note of its own");
    next.tweak = reasons.length > 0 ? reasons.join(" · ") : null;

    return next;
  });

  deliveries.sort((a, b) => a.dateKey.localeCompare(b.dateKey));

  const todayKey = dateKeyOf(startOfDay(new Date()));
  return {
    ...rule,
    deliveries,
    nextKey:
      deliveries.find((d) => d.dateKey >= todayKey && d.state !== "skipped")
        ?.dateKey ?? null,
  };
}

/** Whether a delivery's lines still say what the rule says. */
function sameLines(a: OrderLine[], b: OrderLine[]): boolean {
  if (a.length !== b.length) return false;
  return a.every((l, i) => {
    const r = b[i];
    return (
      l.asset === r.asset &&
      l.product === r.product &&
      (l.gal ?? null) === (r.gal ?? null) &&
      l.topOff === r.topOff
    );
  });
}

/** What this delivery actually carries — its own lines, or the rule's. */
export function deliveryLines(
  rule: RecurringRule,
  d: RuleDelivery
): OrderLine[] {
  return d.lines ?? rule.lines;
}
