/*
  RECURRING ORDERS — V2, THE PARENT/CHILD MODEL.

  This is the shape the product has TODAY, transcribed from the "Recurring
  Orders - 3PL" engineering doc (2026-09-18) rather than guessed. It is one of
  two versions built deliberately side by side so the difference can be SEEN
  rather than argued about:

    V2 (this file) — the recurring order IS an order. It carries the schedule
                     and it is also the first delivery. Everything after it is
                     a child of that order.
    V1 (not built) — the schedule is a RULE that is not an order, and every
                     delivery, including the first, is generated by it.

  WHAT THE DOC FIXES, AND THIS FILE OBEYS

    • A generated order is a COMPLETE, INDEPENDENT ORDER — its own number, its
      own products, its own status, its own history. Not an "occurrence".
    • CHANGES FLOW DOWNWARD ONLY. The parent can rewrite its children; a child
      never writes back.
    • NOTHING GENERATES UNTIL A PARTNER IS LOCKED IN. Not at setup, not on the
      start date. That is why `stalledReason` exists below — a series can be
      perfectly healthy and producing nothing, and the doc names that as the
      commonest support call there is.
    • THE HORIZON IS A ROLLING MONTH — today through one month out, and never
      a date in the past. A schedule that started in March does not back-fill.
    • THE PARENT'S OWN DATE IS SKIPPED, so day one does not produce two orders.

  THE DOUBLE LIFE IS SHOWN, NOT HIDDEN. Because the parent is both the rule and
  a delivery, it appears twice in this module: once as the series, and once as
  the first row inside its own list of deliveries, flagged `isParent`. That is
  not a bug in the model — it IS the model, and V1 exists precisely because of
  it. Smoothing it over in the prototype would hide the thing being compared.

  INVENTED, and flagged: the child order numbers (drawn from a band above the
  seeded ones so they cannot collide), the delivered history before today, and
  the reading of "Custom" as a fortnightly schedule — see `parseSchedule`.
*/

/**
 * §"Where a broker sees it" — the six states a series can be in.
 *
 * SIX WORDS, FOUR TONES. The DS ships four status tones and no more, so two
 * pairs must share one. Cancelled/Ended/Expired all read neutral, which the
 * doc explicitly warns about: "if they share a visual treatment, the
 * difference disappears — and the difference is the whole audit story."
 *
 * The answer is NOT a fifth colour. It is the second line: a series that was
 * stopped by a person says who and when, and one that simply ran out of road
 * says the date it ran out. The word carries the state and the line under it
 * carries the difference — which is the same call the DS makes everywhere
 * else (§11: a status is its word).
 */
export type SeriesStatus =
  | "Upcoming"
  | "Active"
  | "Paused"
  | "Cancelled"
  | "Ended"
  | "Expired";

export const SERIES_STATUSES: SeriesStatus[] = [
  "Upcoming",
  "Active",
  "Paused",
  "Cancelled",
  "Ended",
  "Expired",
];

/** What each one means, in the doc's own words. Shown in the filter menu. */
export const SERIES_STATUS_MEANING: Record<SeriesStatus, string> = {
  Upcoming: "Set up, but the start date hasn't arrived",
  Active: "Running and generating orders",
  Paused: "Temporarily stopped; will resume",
  Cancelled: "Stopped by the broker; stays visible and editable",
  Ended: "The broker deliberately ended it on a date",
  Expired: "Its end date simply passed",
};

/* ---------------------------------------------------------------------------
 * The schedule
 * ------------------------------------------------------------------------ */

const WEEKDAYS = [
  "Sunday",
  "Monday",
  "Tuesday",
  "Wednesday",
  "Thursday",
  "Friday",
  "Saturday",
];

const MONTHS = [
  "January",
  "February",
  "March",
  "April",
  "May",
  "June",
  "July",
  "August",
  "September",
  "October",
  "November",
  "December",
];

export interface Schedule {
  /** The stored string, kept so the sheet can show what was actually set. */
  raw: string;
  /** Plain words for the list — "Every Thursday", not "Weekly On Thursday". */
  label: string;
  /** Whether a given day is on the schedule. */
  hits: (d: Date) => boolean;
  /**
   * WHICH WEEKDAYS IT LANDS ON, 0 = Sunday … 6 = Saturday.
   *
   * The list renders this as a row of seven letters with the ones it hits lit,
   * which answers "when does this run" at a glance in a way "Monthly On First
   * Thursday" never will — a reader scanning twenty rules is comparing
   * SHAPES, and seven dots compare instantly where a sentence has to be read.
   *
   * EMPTY WHERE THE PATTERN IS NOT A WEEKDAY ONE. A yearly date is not a
   * weekday habit, and lighting the weekday it happens to fall on this year
   * would be a lie about what the rule says.
   */
  days: number[];
  /**
   * A SINGLE NAMED BADGE INSTEAD OF THE ROW, where seven lit letters would say
   * less than one word. `Daily` lights all seven, which is a row nobody needs
   * to read; `Yearly` lights none, which is a row that says nothing.
   */
  badge: string | null;
  /** CUSTOM CYCLE — one weekday list per week, drawn as a row each. */
  cycle?: number[][];
  /**
   * THE LINE UNDER THE BADGES — how often the pattern repeats, which the
   * letters cannot carry. The same three lit letters mean every week, every
   * second week, or the first week of the month, and that difference is the
   * whole schedule.
   */
  cadence: string;
}

function dayFromKey(key: string): Date {
  const [y, m, d] = key.split("-").map(Number);
  return new Date(y, m - 1, d);
}

/** Which occurrence of its weekday a date is — 1 for the first Thursday, etc. */
function nthWeekdayOfMonth(d: Date): number {
  return Math.floor((d.getDate() - 1) / 7) + 1;
}

/**
 * Turns the stored frequency string into something that can be both READ and
 * COMPUTED. The seed stores phrases like "Monthly On First Thursday"; the list
 * needs "First Thursday of the month" and the generator needs a predicate, and
 * deriving both from one place is what stops the two drifting apart.
 *
 * "CUSTOM" IS READ AS FORTNIGHTLY, and this is the one liberty taken. The seed
 * ships "Custom" as a frequency with nothing behind it, which would leave those
 * rows with no schedule to describe and no dates to generate — a row that looks
 * broken rather than one that teaches anything. Anchoring it to every second
 * week on the start date's own weekday keeps it derived from real data rather
 * than invented from nothing. What "Custom" should actually offer a broker is
 * an open question, not a decision this file is making.
 */
export function parseSchedule(raw: string, anchorKey: string): Schedule {
  /* THE RULE'S FREQUENCY UNIT, set on an order (Pavan, 2026-10-20). */
  const unit = decodeFrequency(raw);
  if (unit) return toSchedule(unit);
  const anchor = dayFromKey(anchorKey);

  if (raw === "Daily") {
    return {
      raw,
      label: "Every day",
      hits: () => true,
      days: [0, 1, 2, 3, 4, 5, 6],
      badge: "Daily",
      cadence: "Every day, weekends included",
    };
  }

  if (raw === "Every Weekday (Monday To Friday)") {
    return {
      raw,
      label: "Every weekday",
      hits: (d) => d.getDay() >= 1 && d.getDay() <= 5,
      days: [1, 2, 3, 4, 5],
      badge: null,
      cadence: "Every week",
    };
  }

  const weekly = /^Weekly On (\w+)$/.exec(raw);
  if (weekly) {
    const wd = WEEKDAYS.indexOf(weekly[1]);
    return {
      raw,
      label: `Every ${weekly[1]}`,
      hits: (d) => d.getDay() === wd,
      days: [wd],
      badge: null,
      cadence: "Every week",
    };
  }

  const monthly = /^Monthly On (\w+) (\w+)$/.exec(raw);
  if (monthly) {
    const nth = ["First", "Second", "Third", "Fourth"].indexOf(monthly[1]) + 1;
    const wd = WEEKDAYS.indexOf(monthly[2]);
    return {
      raw,
      label: `${monthly[1]} ${monthly[2]} of the month`,
      hits: (d) => d.getDay() === wd && nthWeekdayOfMonth(d) === nth,
      days: [wd],
      badge: null,
      cadence: `${monthly[1]} week of every month`,
    };
  }

  const yearly = /^Annually On (\w+) (\d+)$/.exec(raw);
  if (yearly) {
    const mo = MONTHS.indexOf(yearly[1]);
    const day = Number(yearly[2]);
    return {
      raw,
      label: `Every year on ${yearly[1]} ${day}`,
      hits: (d) => d.getMonth() === mo && d.getDate() === day,
      /* A DATE, NOT A WEEKDAY. September 3 is a Thursday this year and a
         Friday the next; lighting Thursday would describe the calendar rather
         than the rule. */
      days: [],
      badge: "Yearly",
      cadence: `Every year on ${yearly[1]} ${day}`,
    };
  }

  /* Custom — see the note above. */
  const wd = anchor.getDay();
  return {
    raw,
    label: `Every 2 weeks on ${WEEKDAYS[wd]}`,
    days: [wd],
    badge: null,
    cadence: "Every 2 weeks",
    hits: (d) => {
      if (d.getDay() !== wd) return false;
      const weeks = Math.round(
        (startOfDay(d).getTime() - startOfDay(anchor).getTime()) /
          (7 * 86_400_000)
      );
      return weeks % 2 === 0;
    },
  };
}

